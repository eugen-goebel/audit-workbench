def _x01(synth: Synth) -> tuple[Finding, Finding]:
    """(cross-account employee, same-account employee)"""
    findings = [f for f in synth.x if f.rule_id == "X-01"]
    cross = next(f for f in findings if f.details["via_second_account"])
    same = next(f for f in findings if not f.details["via_second_account"])
    return cross, same


def test_x01_cross_account_employee_approves_with_the_second_account(injected: Synth) -> None:
    cross, _ = _x01(injected)
    employee = cross.entity.split(":")[0]
    b08 = {f.entity for f in injected.abc if f.rule_id == "B-08"}
    assert cross.entity == f"{employee}:SOD-GL-01"
    assert cross.severity == Severity.CRITICAL
    assert cross.details["count"] == 3 and set(cross.details["doc_nos"]) <= b08
    assert ["A-05", cross.entity] in cross.details["related"]
    assert all(["B-08", d] in cross.details["related"] for d in cross.details["doc_nos"])
    assert cross.details["held_on_as_of"] is True

    accounts = [a for a in injected.rows("accounts.csv") if a["employee_id"] == employee]
    gl = sorted(a["account_id"] for a in accounts if a["system"] == "GL")
    assert len(gl) == 2
    second = next(a for a in accounts if a["account_id"] == gl[1])
    assert second["created_at"].startswith("2024-12-01")
    roles = [r for r in injected.rows("account_roles.csv") if r["account_id"] in gl]
    for role in roles:
        if role["role_id"] in {"R-GL-CLERK", "R-GL-APPROVER"}:
            assert role["valid_from"] == "2024-12-01", role
    entries = {e["doc_no"]: e for e in injected.rows("journal_entries.csv")}
    for doc_no in cross.details["doc_nos"]:
        assert entries[doc_no]["preparer_account_id"] == gl[0]
        assert entries[doc_no]["approver_account_id"] == gl[1]
    # the ground-truth notes of B-08 say what the data shows
    notes = [
        i["note"] for i in injected.issues("B") if i["rule_id"] == "B-08" and employee in i["note"]
    ]
    assert len(notes) == 3 and all(gl[1] in n and "second GL account" in n for n in notes)


def test_x01_same_account_employee_self_approves_below_the_limit(injected: Synth) -> None:
    _, same = _x01(injected)
    employee = same.entity.split(":")[0]
    assert same.severity == Severity.HIGH  # no entry at or above the manual approval limit
    assert same.details["count"] == 2
    assert float(same.details["max_amount"]) * 100 < MANUAL_LIMIT_CENTS
    assert same.details["via_second_account"] is False
    assert ["A-05", same.entity] in same.details["related"]
    assert not [r for r in same.details["related"] if r[0] == "B-08"]

    hr = next(e for e in injected.rows("hr_employees.csv") if e["employee_id"] == employee)
    assert hr["entry_date"] < "2025-01-01" and hr["exit_date"] == ""
    (account,) = [
        a["account_id"] for a in injected.rows("accounts.csv") if a["employee_id"] == employee
    ]
    assignments = [r for r in injected.rows("account_roles.csv") if r["account_id"] == account]
    since = {r["role_id"]: r["valid_from"] for r in assignments}
    assert "2024-12-01" in since.values()
    assert all(v in {"2024-12-01"} for r, v in since.items() if r != "R-GL-VIEW")

    # no B rule fires on the two entries (nor B-08 in particular)
    b_entities = {f.entity for f in injected.abc if f.rule_id[0] == "B"}
    assert not set(same.details["doc_nos"]) & b_entities
    entries = {e["doc_no"]: e for e in injected.rows("journal_entries.csv")}
    for doc_no in same.details["doc_nos"]:
        assert entries[doc_no]["preparer_account_id"] == account
        assert entries[doc_no]["approver_account_id"] == account
        assert entries[doc_no]["source"] == "manual"


