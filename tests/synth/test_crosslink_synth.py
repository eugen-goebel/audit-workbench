@pytest.mark.parametrize("seed", [12, 27])
def test_exercised_rights_never_start_before_the_joining_date(tmp_path: Path, seed: int) -> None:
    """Seeds 12 and 27 hand the exercised case to someone who joined after 2024-12-01."""
    synth = Synth(generate_bank(tmp_path / f"join{seed}", seed=seed))
    accounts = synth.rows("accounts.csv")
    hr = {e["employee_id"]: e for e in synth.rows("hr_employees.csv")}
    x01 = [f for f in synth.x if f.rule_id == "X-01"]
    assert len(x01) == 2
    for finding in x01:
        employee = finding.entity.split(":")[0]
        mine = {a["account_id"] for a in accounts if a["employee_id"] == employee}
        for account in accounts:
            if account["account_id"] in mine:
                assert account["created_at"][:10] >= hr[employee]["entry_date"], account
        for row in synth.rows("account_roles.csv"):
            if row["account_id"] in mine and row["role_id"].startswith("R-GL-"):
                assert row["valid_from"] >= hr[employee]["entry_date"], (
                    row,
                    hr[employee]["entry_date"],
                )
    for module in "ABCX":
        assert {(f.rule_id, f.entity) for f in synth.found(module)} == synth.keys(module), module


