def test_x03_developer_leavers_commit_after_the_exit(injected: Synth) -> None:
    hr = {e["employee_id"]: e for e in injected.rows("hr_employees.csv")}
    deployers = {
        d.deploying_employee_id
        for d in injected.change.deployments.itertuples()
        if d.deploying_employee_id is not None
    }
    commits = injected.rows("commits.csv")
    a01 = {f.entity: f for f in injected.abc if f.rule_id == "A-01"}
    assert len([f for f in injected.x if f.rule_id == "X-03"]) == 2
    for finding in injected.x:
        if finding.rule_id != "X-03":
            continue
        employee = finding.entity
        assert hr[employee]["org_unit"] == "Entwicklung"
        exit_day = hr[employee]["exit_date"]
        assert finding.details["exit_date"] == exit_day
        assert [a["type"] for a in finding.details["actions"]] == ["commit"]  # one commit
        assert employee not in deployers  # the change is deployed by someone else
        (commit,) = [c for c in commits if c["author_employee_id"] == employee]
        assert commit["committed_ts"][:10] > exit_day and commit["change_id"]
        # A-01 of the same employee: the account was used after the exit
        (account,) = [a for a, f in a01.items() if f.details["employee_id"] == employee]
        assert a01[account].details["logged_in_after_exit"] is True
        assert a01[account].details["last_login"] > commit["committed_ts"]
        assert ["A-01", account] in finding.details["related"]
        note = next(i["note"] for i in injected.issues("A") if i["entity"] == account)
        assert note.endswith("is still active and was used after the exit")
    # no C rule is touched (their ground truth is compared in the test above)
    assert injected.keys("C") == {(f.rule_id, f.entity) for f in injected.found("C")}


