def test_near_miss_gl_conflicts_that_start_after_the_ledger_year(injected: Synth) -> None:
    x01 = {f.entity for f in injected.x if f.rule_id == "X-01"}
    gl_a05 = {e for r, e in injected.keys("A") if r == "A-05" and e.endswith(":SOD-GL-01")}
    open_risks = sorted(gl_a05 - x01)
    assert len(open_risks) == 3  # five GL conflicts in A-05, two of them exercised
    accounts = injected.rows("accounts.csv")
    roles = injected.rows("account_roles.csv")
    for entity in open_risks:
        employee = entity.split(":")[0]
        mine = {a["account_id"] for a in accounts if a["employee_id"] == employee}
        injected_roles = [
            r
            for r in roles
            if r["account_id"] in mine
            and r["role_id"] in {"R-GL-CLERK", "R-GL-MANAGER", "R-GL-APPROVER"}
            and r["valid_from"] >= "2024-12-01"
        ]
        assert injected_roles and {r["valid_from"] for r in injected_roles} == {"2026-07-01"}
        assert ("X-01", entity) not in {(f.rule_id, f.entity) for f in injected.x}


def test_near_miss_sod_employee_approves_another_clerks_entry(injected: Synth) -> None:
    accounts = {a["account_id"]: a["employee_id"] for a in injected.rows("accounts.csv")}
    entries = injected.rows("journal_entries.csv")
    for finding in injected.x:
        if finding.rule_id != "X-01":
            continue
        employee = finding.entity.split(":")[0]
        others = [
            e
            for e in entries
            if e["approver_account_id"]
            and accounts.get(e["approver_account_id"]) == employee
            and accounts.get(e["preparer_account_id"]) != employee
        ]
        assert others, f"{employee} approves no other clerk's entry"
        assert not {e["doc_no"] for e in others} & set(finding.details["doc_nos"])


def test_near_miss_entry_on_the_first_day_of_the_role_assignment(injected: Synth) -> None:
    x02 = {f.entity for f in injected.x if f.rule_id == "X-02"}
    roles = injected.rows("account_roles.csv")
    first_day = [(r["account_id"], r["valid_from"]) for r in roles if r["role_id"] == "R-GL-CLERK"]
    entries = [e for e in injected.rows("journal_entries.csv") if e["source"] == "manual"]
    hits = [
        e
        for e in entries
        for account, day in first_day
        if e["preparer_account_id"] == account and e["entry_ts"][:10] == day
    ]
    # the entry that falls on the first day is also the first entry of that account
    assert len(hits) >= 1
    for e in hits:
        account = e["preparer_account_id"]
        earlier = [x for x in entries if x["preparer_account_id"] == account]
        assert min(x["entry_ts"] for x in earlier) <= e["entry_ts"]
        assert e["doc_no"] not in x02
    # and the rule really does hold the function on that day
    for e in hits:
        assert injected.access.holds_function(
            e["preparer_account_id"], "GL_POST", date.fromisoformat(e["entry_ts"][:10])
        )


def test_near_miss_leaver_commits_on_the_exit_date_and_only_before(injected: Synth) -> None:
    hr = {e["employee_id"]: e for e in injected.rows("hr_employees.csv")}
    x03 = {f.entity for f in injected.x if f.rule_id == "X-03"}
    by_author: dict[str, list[str]] = {}
    for c in injected.rows("commits.csv"):
        by_author.setdefault(c["author_employee_id"], []).append(c["committed_ts"][:10])
    leavers = {e: days for e, days in by_author.items() if hr[e]["exit_date"]}
    near = {e: d for e, d in leavers.items() if e not in x03}
    assert len(leavers) == 4 and len(near) == 2
    on_exit = [e for e, days in near.items() if hr[e]["exit_date"] in days]
    only_before = [e for e, days in near.items() if all(d < hr[e]["exit_date"] for d in days)]
    assert len(on_exit) == 1 and len(only_before) == 1
    for e in near:
        assert all(d <= hr[e]["exit_date"] for d in near[e])
    assert not set(near) & x03
    assert not set(near) & {f.entity for f in injected.x}


