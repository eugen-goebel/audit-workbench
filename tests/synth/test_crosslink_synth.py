def test_every_module_equals_its_ground_truth_exactly(injected: Synth) -> None:
    for module in "ABCX":
        found = injected.found(module)
        got = {(f.rule_id, f.entity) for f in found}
        assert len(found) == len(got), f"module {module}: duplicate findings"
        assert got == injected.keys(module), module


def test_x_counts_match_the_spec(injected: Synth) -> None:
    assert dict(Counter(i["rule_id"] for i in injected.issues("X"))) == X_COUNTS
    assert dict(Counter(f.rule_id for f in injected.x)) == X_COUNTS
    assert len(injected.issues("X")) == 8


def test_ground_truth_notes_are_not_empty_and_entities_are_unique(injected: Synth) -> None:
    issues = injected.issues("X")
    assert all(i["note"] for i in issues)
    assert len({(i["rule_id"], i["entity"]) for i in issues}) == len(issues)
    assert {tuple(sorted(i)) for i in issues} == {("entity", "note", "rule_id")}


def test_a_b_and_c_keys_are_the_ones_of_main(injected: Synth) -> None:
    seed = injected.truth["seed"]
    for module in "AC":
        pairs = sorted([r, e] for r, e in injected.keys(module))
        digest = hashlib.sha256(json.dumps(pairs).encode()).hexdigest()
        assert digest == MAIN_KEYS[seed][module], module


def test_clean_bank_has_no_findings_in_any_module(clean7: Synth) -> None:
    assert clean7.abc == [] and clean7.x == []
    assert clean7.truth["issues"] == []


