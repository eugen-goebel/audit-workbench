"""Audit Workbench dashboard: five pages on one run, rendered with Streamlit.

All numbers come from `audit_workbench.dashboard.views`, the same findings `awb run` prints.
This file only renders them. Start it with `awb dashboard` or `streamlit run dashboard/app.py`.

Settings arrive in environment variables, which `awb dashboard` sets:
AWB_DASHBOARD_DATA_DIR (a data folder; empty = generate a bank), AWB_DASHBOARD_SEED,
AWB_DASHBOARD_AS_OF (YYYY-MM-DD) and AWB_DASHBOARD_MODULE (a, b, c, x or all). The seed can
also come from the URL (`?seed=11`), which wins over the environment.
"""

from __future__ import annotations

import os
from datetime import date
from pathlib import Path

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from audit_workbench.core.findings import Finding
from audit_workbench.dashboard import source, views
from audit_workbench.reporting import ModuleName, module_of, sorted_findings

REPO_URL = "https://github.com/eugen-goebel/audit-workbench"
PAGES = ["Overview", "Module drill-down", "Role graph", "Benford", "Cross-module"]
MODULE_NAMES = {"A": "A  Access", "B": "B  Journal", "C": "C  Change", "X": "X  Cross-module"}
SEVERITY_COLORS = {"LOW": "#9aa5b1", "MEDIUM": "#f2c94c", "HIGH": "#f2994a", "CRITICAL": "#d64545"}
HIGHLIGHT = "#d64545"
ENV_DATA_DIR, ENV_SEED = "AWB_DASHBOARD_DATA_DIR", "AWB_DASHBOARD_SEED"
ENV_AS_OF, ENV_MODULE = "AWB_DASHBOARD_AS_OF", "AWB_DASHBOARD_MODULE"


# --- settings and data ----------------------------------------------------------


def _settings() -> tuple[Path | None, date | None, ModuleName, int]:
    """Data folder, audit date, module and seed from the environment and the URL."""
    data_dir = os.environ.get(ENV_DATA_DIR, "").strip()
    as_of = os.environ.get(ENV_AS_OF, "").strip()
    module = ModuleName(os.environ.get(ENV_MODULE, "").strip().lower() or "all")
    seed = source.parse_seed(st.query_params.get("seed", os.environ.get(ENV_SEED) or None))
    return (
        Path(data_dir) if data_dir else None,
        date.fromisoformat(as_of) if as_of else None,
        module,
        seed,
    )


@st.cache_resource(
    show_spinner="Running all rules (about 3 seconds for a generated bank)...", max_entries=1
)
def _load(directory: str, as_of: str, module: str, seed: int) -> source.Source:
    """One run per (folder, audit date, module, seed). The cache keeps a single entry.

    `st.cache_resource` hands out the object itself; `st.cache_data` would pickle a copy of
    the whole run (hundreds of megabytes) on every interaction.
    """
    return source.load_source(
        Path(directory) if directory else None,
        date.fromisoformat(as_of) if as_of else None,
        ModuleName(module),
        seed,
    )


def _goto(page: str, module: str | None = None, finding_id: str | None = None) -> None:
    """Button callback: open a page, optionally a module's drill-down with a finding selected."""
    st.session_state["page"] = page
    if module is not None:
        st.session_state["drill_module"] = module
        for key in (f"drill_sev_{module}", f"drill_rules_{module}"):
            st.session_state.pop(key, None)
        if finding_id is not None:
            st.session_state[f"drill_finding_{module}"] = finding_id


def _goto_graph(finding_id: str) -> None:
    st.session_state["page"] = "Role graph"
    st.session_state["graph_pick"] = finding_id


def _goto_benford(by: str, key: str) -> None:
    digits = 1 if by == "employee" else 2
    st.session_state["page"] = "Benford"
    st.session_state["benford_by"] = by
    st.session_state[f"benford_digits_{by}"] = digits
    st.session_state[f"benford_group_{by}_{digits}"] = key


def _open_finding(label: str, key: str, finding: Finding) -> None:
    st.button(
        label,
        key=key,
        on_click=_goto,
        args=("Module drill-down", module_of(finding.rule_id), finding.finding_id),
    )


def _banner(loaded: source.Source) -> None:
    if loaded.generated:
        text = f"Synthetic data, seed {loaded.seed}, generated by `audit_workbench.synth`."
    elif loaded.seed is not None:
        text = (
            f"Data folder `{loaded.directory}`: synthetic bank, seed {loaded.seed} "
            "(from ground_truth.json), generated by `audit_workbench.synth`."
        )
    else:
        text = f"Data folder `{loaded.directory}`."
    st.info(
        f"{text} Never real client data. [Source code]({REPO_URL}) · reproduce with `awb generate`."
    )


# --- charts ---------------------------------------------------------------------


def _severity_chart(table: pd.DataFrame) -> go.Figure:
    fig = go.Figure()
    for severity in views.SEVERITIES:
        fig.add_bar(
            name=severity,
            x=list(table.index),
            y=table[severity],
            marker_color=SEVERITY_COLORS[severity],
        )
    fig.update_layout(
        barmode="stack", xaxis_title="Module", yaxis_title="Findings", height=360, margin={"t": 20}
    )
    return fig


def _graph_figure(
    view: views.RoleGraphView, highlight: views.SodHighlight | None, selected_role: str | None
) -> go.Figure:
    pos = {r.node: (r.x, r.y) for r in view.nodes.itertuples()}
    marked_edges = highlight.edges if highlight else set()
    marked_nodes = (highlight.nodes if highlight else set()) | (
        {selected_role} if selected_role else set()
    )

    def lines(edges: list[tuple[str, str]], color: str, width: float, name: str) -> go.Scatter:
        xs: list[float | None] = []
        ys: list[float | None] = []
        for s, t in edges:
            xs += [pos[s][0], pos[t][0], None]
            ys += [pos[s][1], pos[t][1], None]
        return go.Scatter(
            x=xs,
            y=ys,
            mode="lines",
            line={"color": color, "width": width},
            hoverinfo="skip",
            name=name,
        )

    all_edges = list(zip(view.edges["source"], view.edges["target"], strict=True))
    fig = go.Figure()
    fig.add_trace(lines([e for e in all_edges if e not in marked_edges], "#c3cbd4", 1, "contains"))
    if marked_edges:
        fig.add_trace(
            lines([e for e in all_edges if e in marked_edges], HIGHLIGHT, 3.5, "access path")
        )
    for kind, symbol in (("role", "circle"), ("entitlement", "square")):
        part = view.nodes[view.nodes["kind"] == kind]
        colors = [
            HIGHLIGHT if n in marked_nodes else ("#f2994a" if p else "#4c78a8")
            for n, p in zip(part["node"], part["privileged"], strict=True)
        ]
        fig.add_trace(
            go.Scatter(
                x=part["x"],
                y=part["y"],
                mode="markers+text",
                text=part["node"],
                textposition="middle right",
                textfont={"size": 9},
                name=kind + (" (orange: privileged)" if kind == "role" else ""),
                marker={
                    "symbol": symbol,
                    "size": 14,
                    "color": colors,
                    "line": {
                        "width": 2,
                        "color": ["#222" if n in marked_nodes else "#fff" for n in part["node"]],
                    },
                },
                hovertext=[
                    f"{n}: {nm} ({sy})"
                    for n, nm, sy in zip(part["node"], part["name"], part["system"], strict=True)
                ],
                hoverinfo="text",
            )
        )
    fig.update_layout(
        height=620,
        margin={"t": 10, "l": 10, "r": 140},
        xaxis={"visible": False, "range": [-0.3, float(view.nodes["x"].max()) + 1.5]},
        yaxis={"visible": False},
        legend={"orientation": "h"},
    )
    return fig


def _benford_figure(group: views.BenfordGroup) -> go.Figure:
    table = views.benford_table(group)
    fig = go.Figure()
    fig.add_bar(x=table["digit"], y=table["observed"], name="observed", marker_color="#4c78a8")
    fig.add_scatter(
        x=table["digit"],
        y=table["expected"],
        name="expected (Benford)",
        mode="lines+markers",
        line={"color": HIGHLIGHT},
    )
    fig.update_layout(
        xaxis_title="Leading digit(s)",
        yaxis_title="Share",
        height=340,
        margin={"t": 20},
        legend={"orientation": "h"},
    )
    return fig


# --- pages ----------------------------------------------------------------------


def page_overview(loaded: source.Source, module: ModuleName) -> None:
    st.header("Overview")
    ov = views.overview(loaded.run, module)
    k = ov.kpis
    cols = st.columns(4)
    cols[0].metric("Findings", k.findings)
    cols[1].metric("CRITICAL", k.critical)
    cols[2].metric("Rules fired / ran", f"{k.rules_fired} / {k.rules_run}")
    cols[3].metric("Entities affected", k.entities)

    quality = views.evidence_quality(loaded.run, loaded.truth, module)
    if quality is not None:
        st.subheader("Evidence quality")
        left, right = st.columns(2)
        left.metric("Injected issues matched", f"{len(quality.matched)} / {len(quality.expected)}")
        right.metric("Findings without a ground-truth counterpart", len(quality.unexpected))
        st.caption("Same comparison as `awb check-ground-truth`.")

    st.subheader("Findings per module and severity")
    st.plotly_chart(_severity_chart(ov.by_module_severity), width="stretch")

    st.subheader("Rules")
    st.caption("Every rule that ran; a rule without findings shows 0.")
    st.dataframe(
        ov.top_rules[["rule", "title", "module", "count", "severity_mix"]],
        hide_index=True,
        width="stretch",
    )

    st.subheader("Data basis")
    st.caption("One row per input file; the findings rest on exactly these bytes.")
    st.dataframe(
        ov.data_basis[["file", "rows", "columns", "sha256_prefix", "sha256"]],
        hide_index=True,
        width="stretch",
    )


def _show_detail(loaded: source.Source, finding: Finding) -> None:
    detail = views.finding_detail(loaded.run, finding)
    st.subheader(f"{finding.rule_id}: {detail.rule_title}")
    st.caption(
        f"Rule version {detail.rule_version} · finding {finding.finding_id} · "
        f"{finding.severity.name}"
    )
    st.markdown(f"**What it tests.** {detail.rule_summary}")
    st.markdown(f"**Entity.** `{finding.entity}`")
    st.markdown(f"**Description.** {finding.description}")
    with st.expander("Parameters"):
        st.json(detail.params)
    st.markdown("**Regulation references**")
    if not detail.references:
        st.write("none")
    for ref in detail.references:
        st.markdown(f"- {ref.label}" + (f" ([source]({ref.url}))" if ref.url else ""))
        if ref.quote:
            st.markdown(f"> {ref.quote}")
    st.markdown("**Evidence files**")
    st.dataframe(
        pd.DataFrame(
            [
                {"file": e.file, "sha256 prefix": e.prefix, "sha256": e.sha256}
                for e in detail.evidence
            ]
        ),
        hide_index=True,
        width="stretch",
    )
    if detail.detail_lines:
        st.markdown("**Details**")
        st.code("\n".join(detail.detail_lines), language=None)
    for raw in detail.raw_rows:
        shown = f"{len(raw.rows)} of {raw.total}" if raw.truncated else str(raw.total)
        with st.expander(f"Raw rows of {raw.file} ({raw.key}): {shown}"):
            st.dataframe(raw.rows, hide_index=True, width="stretch")


def page_drilldown(loaded: source.Source, module: ModuleName) -> None:
    st.header("Module drill-down")
    letters = [m for m in views.MODULES if module is ModuleName.all or m == module.value.upper()]
    letter = st.radio(
        "Module", letters, format_func=MODULE_NAMES.get, horizontal=True, key="drill_module"
    )
    rules = views.module_rules(letter)
    titles = dict(rules)
    all_severities = list(reversed(views.SEVERITIES))
    left, right = st.columns(2)
    severities = left.multiselect(
        "Severity", all_severities, default=all_severities, key=f"drill_sev_{letter}"
    )
    chosen = right.multiselect(
        "Rule",
        [r for r, _ in rules],
        default=[r for r, _ in rules],
        format_func=lambda r: f"{r}  {titles[r]}",
        key=f"drill_rules_{letter}",
    )
    findings = views.filter_findings(loaded.run.findings, letter, set(severities), set(chosen))
    st.write(f"{len(findings)} findings")
    st.dataframe(
        views.findings_frame(findings).drop(columns=["module"]), hide_index=True, width="stretch"
    )
    if not findings:
        return
    by_id = {f.finding_id: f for f in findings}
    picked = st.selectbox(
        "Open a finding",
        list(by_id),
        format_func=lambda i: f"{by_id[i].severity.name:<8} {by_id[i].rule_id}  {by_id[i].entity}",
        key=f"drill_finding_{letter}",
    )
    finding = by_id[picked]
    _show_detail(loaded, finding)
    if finding.rule_id == "A-05":
        st.button(
            "Show this conflict in the role graph",
            key=f"to_graph_{finding.finding_id}",
            on_click=_goto_graph,
            args=(finding.finding_id,),
        )
    if finding.rule_id in ("B-01", "B-02"):
        st.button(
            "Show the digit distribution",
            key=f"to_benford_{finding.finding_id}",
            on_click=_goto_benford,
            args=("employee" if finding.rule_id == "B-01" else "account", finding.entity),
        )


def page_role_graph(loaded: source.Source) -> None:
    st.header("Role graph")
    access = loaded.run.access
    if access is None:
        st.info("This run has no module A data.")
        return
    view = views.role_graph_view(access)
    roles = view.nodes[view.nodes["kind"] == "role"]
    st.caption(
        f"{len(roles)} roles and {len(view.nodes) - len(roles)} entitlements, "
        f"{len(view.edges)} edges. An edge points from a role to what it contains."
    )
    conflicts = {f.finding_id: f for f in loaded.run.findings if f.rule_id == "A-05"}
    pick = st.selectbox(
        "Highlight an A-05 conflict",
        ["(none)", *conflicts],
        format_func=lambda i: (
            i if i == "(none)" else f"{conflicts[i].entity}  ({conflicts[i].severity.name})"
        ),
        key="graph_pick",
    )
    highlight = views.sod_highlight(access, conflicts[pick]) if pick in conflicts else None
    role = st.selectbox("Look up a role", ["(none)", *roles["node"]], key="graph_role")
    selected = None if role == "(none)" else role
    st.plotly_chart(_graph_figure(view, highlight, selected), width="stretch")

    if highlight is not None:
        st.subheader("The two paths behind the conflict")
        for fn, path in highlight.paths.items():
            st.markdown(f"**{fn}**: `{' -> '.join(path)}`")
        st.write("Accounts holding them: " + ", ".join(highlight.accounts))
        _open_finding("Open the finding", f"graph_open_{pick}", conflicts[pick])
    if selected is not None:
        info = views.role_info(access, selected)
        st.subheader(f"{info.role_id}: {info.name}")
        st.caption(f"System {info.system}" + (" · privileged" if info.privileged else ""))
        st.markdown("**Grants roles (transitively):** " + (", ".join(info.grants_roles) or "none"))
        st.markdown("**Grants entitlements**")
        st.dataframe(info.entitlements, hide_index=True, width="stretch")
        st.markdown(f"**Accounts holding it on the audit date ({len(info.accounts)})**")
        st.dataframe(info.accounts, hide_index=True, width="stretch")


def page_benford(loaded: source.Source) -> None:
    st.header("Benford")
    journal = loaded.run.journal
    if journal is None:
        st.info("This run has no module B data.")
        return
    by_label = {"employee": "Per employee (B-01)", "account": "Per GL account (B-02)"}
    by = st.radio(
        "Group by", list(by_label), format_func=by_label.get, horizontal=True, key="benford_by"
    )
    default_digits = 1 if by == "employee" else 2
    digits = st.radio(
        "Digits",
        [1, 2],
        index=default_digits - 1,
        format_func=lambda d: "first digit" if d == 1 else "first two digits",
        horizontal=True,
        key=f"benford_digits_{by}",
    )
    view = views.benford_view(journal, by, digits=digits, findings=loaded.run.findings)  # type: ignore[arg-type]
    testable = [g for g in view.groups if g.testable]
    st.caption(
        f"{len(view.groups)} groups, {len(testable)} with at least {view.min_n:,} amounts. "
        "Smaller groups are shown as not testable, not as clean. "
        f"Nonconformity limit: MAD above {view.threshold}."
    )
    st.dataframe(
        pd.DataFrame(
            {
                "group": [g.key for g in view.groups],
                "amounts": [g.n for g in view.groups],
                "MAD": [round(g.mad, 5) for g in view.groups],
                "chi-square": [round(g.chi_square, 2) for g in view.groups],
                "status": [g.status for g in view.groups],
                "finding": [g.finding_id or "" for g in view.groups],
            }
        ),
        hide_index=True,
        width="stretch",
    )
    by_key = {g.key: g for g in view.groups}
    keys = list(by_key)
    flagged = [g.key for g in view.groups if g.finding_id]
    chosen = st.selectbox(
        "Show a group",
        keys,
        index=keys.index(flagged[0]) if flagged else 0,
        key=f"benford_group_{by}_{digits}",
    )
    group = by_key[chosen]
    cols = st.columns(4)
    cols[0].metric("Amounts", f"{group.n:,}")
    cols[1].metric("MAD", f"{group.mad:.5f}")
    cols[2].metric("Limit", f"{view.threshold}")
    cols[3].metric("Status", group.status)
    st.plotly_chart(_benford_figure(group), width="stretch")
    if group.finding_id:
        finding = next(f for f in loaded.run.findings if f.finding_id == group.finding_id)
        _open_finding(
            f"Open finding {finding.rule_id} for {group.key}",
            f"benford_open_{group.finding_id}",
            finding,
        )


def page_cross(loaded: source.Source) -> None:
    st.header("Cross-module")
    chains = views.cross_chains(loaded.run)
    if not chains:
        st.info("No cross-module findings in this run (module X not run, or none found).")
        return
    st.caption(
        "Each chain joins the modules through the key shown; "
        "the buttons open the findings behind each step."
    )
    for chain in chains:
        f = chain.finding
        with st.expander(f"{f.rule_id} · {f.severity.name} · {chain.link_key}"):
            st.markdown(f"**{chain.title}.** {f.description}")
            st.markdown(f"**Linking key:** {chain.link_key} · modules {', '.join(chain.modules)}")
            for i, step in enumerate(chain.steps):
                st.markdown(f"{i + 1}. **{step.module}** · {step.kind}: {step.label}")
                hit = next((r for r in chain.related if r.finding_id == step.finding_id), None)
                if hit is not None:
                    _open_finding(f"Open {hit.rule_id} {hit.entity}", f"x_{f.finding_id}_{i}", hit)
            _open_finding(f"Open the {f.rule_id} finding", f"x_open_{f.finding_id}", f)


# --- main -----------------------------------------------------------------------


def main() -> None:
    st.set_page_config(page_title="Audit Workbench", layout="wide")
    st.title("Audit Workbench")
    try:
        data_dir, as_of, module, seed = _settings()
    except ValueError as exc:  # includes InvalidSeedError and a bad date or module
        st.error(f"Invalid setting: {exc}")
        st.stop()
    try:
        loaded = _load(str(data_dir or ""), as_of.isoformat() if as_of else "", module.value, seed)
    except source.SourceError as exc:
        st.error(str(exc))
        st.stop()

    _banner(loaded)
    with st.sidebar:
        st.radio("Page", PAGES, key="page")
        if loaded.generated:
            typed = st.text_input("Seed", value=str(seed), help="As in `awb generate --seed N`.")
            if typed.strip() != str(seed):
                try:
                    source.parse_seed(typed)
                except source.InvalidSeedError as exc:
                    st.error(str(exc))
                else:
                    st.query_params["seed"] = typed.strip()
                    st.rerun()
        ordered = sorted_findings(loaded.run.findings)
        st.download_button(
            "Findings as CSV", views.findings_csv(ordered), "findings.csv", "text/csv"
        )
        st.download_button(
            "Findings as markdown", views.findings_markdown(ordered), "findings.md", "text/markdown"
        )

    page = st.session_state["page"]
    if page == "Overview":
        page_overview(loaded, module)
    elif page == "Module drill-down":
        page_drilldown(loaded, module)
    elif page == "Role graph":
        page_role_graph(loaded)
    elif page == "Benford":
        page_benford(loaded)
    else:
        page_cross(loaded)


main()
